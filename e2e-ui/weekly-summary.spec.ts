// AI weekly summary card on Home (Prompt 51). Every /api call is mocked.
import { expect, test, type Page } from "@playwright/test";

const FACTS = {
  weekStart: "2026-11-09",
  weekEnd: "2026-11-15",
  activeClients: 3,
  checkIns: 7,
  avgAdherence: 84,
  avgAdherenceChange: 4,
  assignmentsCompleted: 5,
  atRiskClients: 1,
};
const AI_TEXT = "3 active clients logged 7 check-ins.\nAdherence averaged 84%.\n\nSuggested actions:\n- Message the client who needs attention\n- Plan next week";
const FACTS_TEXT = "- Active clients this week: 3\n- Check-ins logged: 7\n- Average adherence: 84% (up 4 points on last week)\n- Plans completed: 5\n- Clients needing attention: 1 client";

const CLIENTS = [
  { id: "c-maya", coachId: "coach-1", name: "Maya Patel", goal: "Fat loss", age: 29, weightKg: 68, heightCm: 165, level: "Intermediate", focus: "", notes: "", createdAt: "2026-10-01T00:00:00.000Z" },
];

const card = (page: Page) => page.getByRole("region", { name: "AI weekly summary" });
const generateButton = (page: Page) => card(page).getByRole("button", { name: "Generate this week's summary" });

/** Mocks the whole app; `post` decides what POST /api/weekly-summary answers. */
async function openHome(page: Page, options: { saved?: unknown; post?: (calls: number) => { status: number; json: unknown } } = {}) {
  let saved = options.saved ?? null;
  let posts = 0;
  await page.route("**/api/**", (route) => {
    const url = new URL(route.request().url());
    const path = url.pathname;
    if (path === "/api/auth/me") return route.fulfill({ json: { id: "coach-1", name: "Ana", email: "ana@example.com", createdAt: "2026-11-01T00:00:00.000Z" } });
    if (path === "/api/clients") return route.fulfill({ json: CLIENTS });
    if (path === "/api/weekly-summary" && route.request().method() === "POST") {
      posts += 1;
      const reply = options.post ? options.post(posts) : { status: 201, json: { weekStart: FACTS.weekStart, summary: { weekStart: FACTS.weekStart, text: AI_TEXT, facts: FACTS, createdAt: "2026-11-11T10:00:00.000Z", source: "ai" } } };
      if (reply.status === 201) saved = (reply.json as { summary: unknown }).summary;
      return route.fulfill({ status: reply.status, json: reply.json });
    }
    if (path === "/api/weekly-summary") return route.fulfill({ json: { weekStart: FACTS.weekStart, summary: saved } });
    if (path === "/api/tasks/today") return route.fulfill({ json: { date: "2026-11-11", tasks: [] } });
    if (path === "/api/checkins/recent") return route.fulfill({ json: { items: [] } });
    if (path === "/api/at-risk") return route.fulfill({ json: { date: "2026-11-11", clients: [] } });
    return route.fulfill({ json: [] });
  });
  await page.goto("/app");
  await page.getByRole("tab", { name: "Home" }).click();
  await expect(card(page)).toBeVisible();
}

test("empty state, then the AI summary with its week and no error", async ({ page }) => {
  await openHome(page);
  await expect(card(page)).toContainText("No summary yet for this week.");
  await generateButton(page).click();
  await expect(card(page)).toContainText("3 active clients logged 7 check-ins.");
  await expect(card(page)).toContainText("Suggested actions:");
  await expect(card(page)).toContainText("Week of 2026-11-09");
  await expect(card(page)).not.toContainText("unavailable");
});

test("a saved summary is there on load and is not regenerated by accident", async ({ page }) => {
  const saved = { weekStart: FACTS.weekStart, text: AI_TEXT, facts: FACTS, createdAt: "2026-11-11T10:00:00.000Z", source: "ai" };
  await openHome(page, {
    saved,
    post: () => ({ status: 409, json: { error: "This week's summary is already saved. Confirm to replace it." } }),
  });
  await expect(card(page)).toContainText("Adherence averaged 84%.");

  // Pressing Generate asks first; cancelling keeps the saved text.
  await generateButton(page).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog).toContainText("Replace this week's summary?");
  await dialog.getByRole("button", { name: "Cancel" }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await expect(card(page)).toContainText("Adherence averaged 84%.");
});

test("confirming replaces this week's summary", async ({ page }) => {
  const saved = { weekStart: FACTS.weekStart, text: "Old summary text.", facts: FACTS, createdAt: "2026-11-11T10:00:00.000Z", source: "ai" };
  await openHome(page, {
    saved,
    post: (calls) =>
      calls === 1
        ? { status: 409, json: { error: "This week's summary is already saved. Confirm to replace it." } }
        : { status: 201, json: { weekStart: FACTS.weekStart, summary: { ...saved, text: "Replaced summary text." } } },
  });
  await generateButton(page).click();
  await page.getByRole("dialog").getByRole("button", { name: "Replace summary" }).click();
  await expect(card(page)).toContainText("Replaced summary text.");
  await expect(card(page)).not.toContainText("Old summary text.");
});

test("when the AI is unavailable the card shows the facts, never an error page", async ({ page }) => {
  await openHome(page, {
    post: () => ({ status: 201, json: { weekStart: FACTS.weekStart, summary: { weekStart: FACTS.weekStart, text: FACTS_TEXT, facts: FACTS, createdAt: "2026-11-11T10:00:00.000Z", source: "facts" } } }),
  });
  await generateButton(page).click();
  await expect(card(page)).toContainText("The AI was unavailable, so here are this week's facts.");
  await expect(card(page)).toContainText("Check-ins logged: 7");
  await expect(card(page)).toContainText("Plans completed: 5");
  await expect(page.getByRole("tab", { name: "Home" })).toBeVisible(); // still the normal page
});

test("a failed request shows a plain message and keeps the page usable", async ({ page }) => {
  await openHome(page, { post: () => ({ status: 500, json: { error: "Something went wrong" } }) });
  await generateButton(page).click();
  await expect(card(page).getByRole("alert")).toContainText("We couldn't generate the summary just now.");
  await expect(generateButton(page)).toBeEnabled();
});
