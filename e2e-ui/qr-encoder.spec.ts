test("picks the smallest version that fits a join link and throws past version 6", () => {
  expect(encodeQr("https://app.repsy.fit/join/ANNA-7K2Q8M").version).toBe(3);
  expect(encodeQr("http://localhost:5173/join/ANNA-7K2Q8M").version).toBe(3);
  expect(encodeQr("a".repeat(106)).version).toBe(6);
  expect(() => encodeQr("a".repeat(107))).toThrow("too long");
});

test("has the finder patterns, timing lines and the dark module in place", () => {
  const q = encodeQr("https://app.repsy.fit/join/ANNA-7K2Q8M");
  const n = q.size;
  const finder = ["1111111", "1000001", "1011101", "1011101", "1011101", "1000001", "1111111"];
  const at = (x0: number, y0: number) => q.modules.slice(y0, y0 + 7).map((r) => r.slice(x0, x0 + 7).map((b) => (b ? "1" : "0")).join(""));
  expect(at(0, 0)).toEqual(finder);
  expect(at(n - 7, 0)).toEqual(finder);
  expect(at(0, n - 7)).toEqual(finder);
  for (let i = 8; i < n - 8; i++) {
    expect(q.modules[6][i]).toBe(i % 2 === 0);
    expect(q.modules[i][6]).toBe(i % 2 === 0);
  }
  expect(q.modules[n - 8][8]).toBe(true);
});
