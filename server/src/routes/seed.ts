// POST /api/seed/six-month-demo - adds the 10 six-month clients (26 check-ins + 5 plans each),
// skipping any whose name already exists, so nothing is ever duplicated. Returns the clients it created: 201, or 200 [] when all 10 were already there.
seedRouter.post(
  "/six-month-demo",
  asyncHandler(async (_req, res) => {
    const created = await prisma.$transaction(
      async (tx) => {
        await tx.$executeRaw`SELECT pg_advisory_xact_lock(${SEED_LOCK_KEY})`;
        const existing = await tx.client.findMany({
          where: { coachId: DEMO_COACH_ID, name: { in: SIX_MONTH_ROSTER.map((c) => c.name) } },
          select: { name: true },
        });
        const taken = new Set(existing.map((c) => c.name));
        const base = Date.now();

        const clients = [];
        for (const [i, c] of SIX_MONTH_ROSTER.entries()) {
          if (taken.has(c.name)) continue;
          const { startKg: _start, endKg, baseAdherence: _a, baseWorkouts: _w, ...profile } = c;
          clients.push(
            await tx.client.create({
              data: {
                ...profile,
                weightKg: endKg,
                coachId: DEMO_COACH_ID,
                createdAt: new Date(base + i),
                progressLogs: {
                  create: sixMonthLogs(c).map((log) => ({ ...log, coachId: DEMO_COACH_ID })),
                },
                assignments: {
                  create: sixMonthAssignments().map((a) => ({
                    ...a,
                    coachId: DEMO_COACH_ID,
                    // createdAt on the plan's date, so the Planner lists newest first.
                    createdAt: new Date(`${a.date}T09:00:00Z`),
                  })),
                },
              },
            }),
          );
        }
        return clients;
      },
      SEED_TX_OPTIONS,
    );

    res.status(created.length ? 201 : 200).json(created);
  }),
);
