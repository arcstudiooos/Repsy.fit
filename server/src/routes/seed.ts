const SIX_MONTH_START = "2026-05-11";
const SIX_MONTH_WEEKS = 26; // 2026-05-11 ... 2026-11-02

/** Small seeded random generator (mulberry32), so every re-run gives the same history. */
function seededRandom(seedText: string) {
  let h = 2166136261;
  for (const ch of seedText) h = Math.imul(h ^ ch.charCodeAt(0), 16777619);
  let a = h >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const clamp = (n: number, lo: number, hi: number) => Math.min(hi, Math.max(lo, n));

/** One client's 26 weekly check-ins, oldest first. Weight moves smoothly from startKg to endKg
 *  with a small wobble; adherence (55-98) and workouts (1-7) stay near the person's base. */
export function sixMonthLogs(c: SixMonthClient) {
  const random = seededRandom(c.name);
  const start = new Date(`${SIX_MONTH_START}T00:00:00Z`).getTime();
  const last = SIX_MONTH_WEEKS - 1;
  return Array.from({ length: SIX_MONTH_WEEKS }, (_, i) => {
    const trend = c.startKg + ((c.endKg - c.startKg) * i) / last;
    const wobble = i === 0 || i === last ? 0 : (random() - 0.5) * 0.5; // +/-0.25 kg
    const adherence = clamp(Math.round(c.baseAdherence + (random() - 0.5) * 16), 55, 98); // base +/-8
    const r = random();
    const workoutShift = r < 0.05 ? -2 : r < 0.25 ? -1 : r < 0.75 ? 0 : r < 0.95 ? 1 : 2;
    return {
      date: isoDate(new Date(start + i * 7 * DAY_MS)),
      weightKg: round1(trend + wobble),
      adherence,
      workoutsDone: clamp(c.baseWorkouts + workoutShift, 1, 7),
      note: i === 0 ? "Started program" : i === last ? "6-month review" : "",
    };
  });
}

